(function ($) {
  $(document).ready(function () {
    // --- preserve your existing offcanvas margin behavior ---
    const offcanvasEl = document.getElementById("mobileNav");
    const pageContent = document.getElementById("pageContent");
    if (offcanvasEl && pageContent) {
      offcanvasEl.addEventListener("show.bs.offcanvas", function () {
        pageContent.style.marginRight = "280px";
      });
      offcanvasEl.addEventListener("hide.bs.offcanvas", function () {
        pageContent.style.marginRight = "0";
      });
    }

    // --- transform WP/Bootstrap dropdowns inside the offcanvas into collapse accordions ---
    var $accordion = $("#mobileAccordion");
    if ($accordion.length) {
      var counter = 0;

      $accordion.find(".menu-item-has-children").each(function () {
        counter++;
        var $li = $(this);
        // the top-level link that triggers the dropdown
        var $link = $li.children("a").first();
        // submenu UL generated by walker (common classes: .dropdown-menu or .sub-menu)
        var $submenu = $li.children("ul.dropdown-menu, ul.sub-menu").first();

        if ($link.length && $submenu.length) {
          var id = "mSubmenu" + counter;

          // build button that matches your markup
          var labelHtml = $link.html(); // keep inner HTML (text + markup if any)
          var $button = $("<button/>", {
            class: "toggle bg-transparent border-0",
            type: "button",
            "data-bs-toggle": "collapse",
            "data-bs-target": "#" + id,
            "aria-expanded": "false",
            "aria-controls": id,
            html: labelHtml + ' <i class="bi bi-chevron-down"></i>',
          });

          // replace the link with button (removes default dropdown behavior)
          $link.replaceWith($button);

          // create collapse container and move submenu items into .sub-item blocks
          var $collapse = $("<div/>", {
            class: "collapse",
            id: id,
            "data-bs-parent": "#mobileAccordion",
          });

          // Move each li > a into .sub-item > a
          $submenu.children("li").each(function () {
            var $childA = $(this).find("a").first();
            if ($childA.length) {
              var $subItem = $("<div/>", { class: "sub-item" });
              $childA.appendTo($subItem); // move <a> inside .sub-item
              $subItem.appendTo($collapse);
            }
          });

          // replace original <ul> with the collapse div
          $submenu.replaceWith($collapse);
        }
      });
    }

    // optional: toggle .active class on clicks inside mobile accordion
    $(document).on(
      "click",
      "#mobileAccordion .nav-link, #mobileAccordion .toggle",
      function () {
        $("#mobileAccordion .nav-link, #mobileAccordion .toggle").removeClass(
          "active"
        );
        $(this).addClass("active");
      }
    );
  });
})(jQuery);

